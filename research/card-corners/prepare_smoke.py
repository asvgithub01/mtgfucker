"""Own procedural calibration textures, NOT MTG training data; output must be new."""
import argparse,json
from pathlib import Path
from PIL import Image,ImageDraw
from prepare import prepare

def main():
    p=argparse.ArgumentParser();p.add_argument('--root',required=True);a=p.parse_args()
    root=Path(a.root).resolve();root.mkdir(parents=True,exist_ok=False)
    sources=root/'sources';sources.mkdir();rows=[]
    for i in range(4):
        im=Image.new('RGB',(320,448),['black','white','navy','brown'][i]);d=ImageDraw.Draw(im)
        d.rectangle((12,12,308,436),fill=['orange','lightblue','pink','lightgreen'][i])
        d.text((20,20),f'TOP - CALIBRATION {i}',fill='black')
        for k,(x,y) in enumerate([(20,45),(270,45),(270,400),(20,400)]):
            d.rectangle((x,y,x+18,y+18),fill=['red','green','blue','yellow'][k]);d.text((x,y+20),str(k),fill='black')
        path=sources/f'calibration-{i}.png';im.save(path)
        rows.append(dict(path=str(path),group=f'procedural-{i}',split='validation' if i==3 else 'train'))
    (root/'textures.json').write_text(json.dumps(rows,indent=2))
    (root/'config.json').write_text(json.dumps(prepare(rows,root/'renders'/'smoke-01',120),indent=2))
    (root/'README.txt').write_text('Procedural geometry/UV calibration only. No MTG accuracy claims. Generated by prepare_smoke.py. Run Unity, validate overlays, then prepare a separate reviewed texture dataset.')
    print(root/'config.json')

if __name__=='__main__':main()
